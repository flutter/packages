class _MockHttpClient extends Fake implements HttpClient {
  @override
  bool autoUncompress = false;

  @override
  Future<HttpClientRequest> getUrl(Uri url) async => _MockHttpClientRequest();
}

class _MockHttpClientRequest extends Fake implements HttpClientRequest {
  @override
  final HttpHeaders headers = _MockHttpHeaders();

  @override
  Future<HttpClientResponse> close() async => _MockHttpClientResponse();
}

class _MockHttpHeaders extends Fake implements HttpHeaders {}

class _MockHttpClientResponse extends Fake implements HttpClientResponse {
  @override
  int get statusCode => HttpStatus.ok;

  @override
  int get contentLength => _kTransparentImage.length;

  @override
  HttpClientResponseCompressionState get compressionState =>
      HttpClientResponseCompressionState.notCompressed;

  @override
  StreamSubscription<List<int>> listen(
    void Function(List<int> event)? onData, {
    Function? onError,
    void Function()? onDone,
    bool? cancelOnError,
  }) {
    return Stream<List<int>>.value(_kTransparentImage).listen(
      onData,
      onError: onError,
      onDone: onDone,
      cancelOnError: cancelOnError,
    );
  }
}

void main() {
  testWidgets(
    'CircleAvatar configures circular DecorationImage from NetworkImage',
    (WidgetTester tester) async {
      await HttpOverrides.runZoned(() async {
        await tester.pumpWidget(const example.ExampleApp());
        await tester.runAsync(() async {
          await precacheImage(
            const NetworkImage(example.userAvatarUrl),
            tester.element(find.byType(CircleAvatar)),
          );
        });
        await tester.pumpAndSettle();

        final RenderConstrainedBox box = tester.renderObject(
          find.byType(CircleAvatar),
        );
        final RenderDecoratedBox decoratedBox =
            box.child! as RenderDecoratedBox;
        final BoxDecoration decoration =
            decoratedBox.decoration as BoxDecoration;

        expect(decoration.shape, BoxShape.circle);
        expect(decoration.image?.fit, BoxFit.cover);
        expect(
          decoration.image?.image,
          const NetworkImage(example.userAvatarUrl),
        );
      }, createHttpClient: (SecurityContext? _) => _MockHttpClient());
    },
  );
}
